/** `isSameLocation` as of 2026-11-08: token containment, whole-set for generic words. */
export function legacyIsSameLocation(a, b) {
    const ta = legacyLocationTokens(a);
    const tb = legacyLocationTokens(b);
    if (containment(ta, tb) < 0.99) return false;
    if (ta.size === tb.size) return true;
    const smaller = ta.size < tb.size ? ta : tb;
    return [...smaller].some(token => !GENERIC_PLACE_WORDS.has(token));
}

/** The settlement no-fold as of 2026-11-08: a candidate naming a town plus more words is a place WITHIN it. */
function legacyNamesPlaceWithinSettlement(record, target) {
    if (record?.type !== 'settlement' && record?.settlementScale !== true) return false;
    const recordTokens = legacyLocationTokens(record.name);
    const targetTokens = legacyLocationTokens(target);
    if (targetTokens.size <= recordTokens.size) return false;
    const comma = String(target).lastIndexOf(',');
    if (comma > 0) {
        const head = legacyLocationTokens(String(target).slice(0, comma));
        if (head.size === recordTokens.size && containment(head, recordTokens) >= 0.99) return false;
    }
    return coverage(recordTokens, targetTokens) >= 0.99;
}

/**
 * `findLocationRecord` as of 2026-11-08: exact name or alias anywhere in the
 * list, else the first record whose NAME the target contains (never an alias),
 * a settlement never claiming a place within it. Returns the index or -1.
 */
export function legacyFindLocationRecord(locations = [], name) {
    const target = cleanText(name, 120);
    if (!target) return -1;
    const list = Array.isArray(locations) ? locations : [];
    const lower = target.toLowerCase();
    const exact = list.findIndex(record => record
        && (record.name?.toLowerCase() === lower
            || (record.aliases || []).some(alias => typeof alias === 'string' && alias.toLowerCase() === lower)));
    if (exact !== -1) return exact;
    return list.findIndex(record => record && typeof record.name === 'string' && legacyIsSameLocation(record.name, target)
        && !legacyNamesPlaceWithinSettlement(record, target));
}

/**
 * Every place string a save holds outside the registry: where the hero
 * stands, where each person was last seen and is based, where a card or a
 * journal entry was stamped, where a front's directive placed its symptom.
 * These are what the exact lookups read; the migration seeds each one as an
 * alias of the record the frozen rung resolved it to.
 */
export function legacyPlaceNamesInSave(save = {}) {
    const names = new Set();
    const add = (value) => {
        if (typeof value === 'string' && value.trim()) names.add(value.trim());
    };
    add(save.currentLocation);
    for (const npc of Array.isArray(save.npcs) ? save.npcs : []) {
        add(npc?.lastLocation);
        add(npc?.basedIn);
    }
    for (const card of Array.isArray(save.storyMemory) ? save.storyMemory : []) add(card?.location);
    for (const fact of Array.isArray(save.worldFacts) ? save.worldFacts : []) add(fact?.location);
    for (const entry of Array.isArray(save.journal) ? save.journal : []) add(entry?.location);
    for (const front of Array.isArray(save.fronts) ? save.fronts : []) {
        for (const directive of Array.isArray(front?.directives) ? front.directives : []) add(directive?.where);
    }
    return [...names];
}
