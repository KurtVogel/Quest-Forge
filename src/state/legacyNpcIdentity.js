/**
 * The FROZEN copy of the roster's fuzzy name identity, for the one-time save
 * migration only (identity by reference, lane 6, 2026-11-08; DECISIONS.md
 * decision 4: "a one-time migration seeds aliases using today's namesMatch,
 * frozen in the migration file and called nowhere else"). Nothing in play
 * reads this file: the live roster compares an id, an exact name or an exact
 * alias (`findNpcByRef`), and the live `namesMatch` only shortlists for the
 * Scribe. This copy is what `namesMatch` and `dedupeNpcRoster` were on
 * 2026-11-07, so an old save gets the same answer the game gave it then,
 * once, and the result is written down as aliases and folded records.
 *
 * Do not edit this file to track later changes to the live matcher — that is
 * the point of it.
 */
import { appendBondMoments, appendCallbackHooks, isGenericCreatureName, mergeNpcDossierText, normalizeImpressions, normalizeNpcRecord, NPC_DURABLE_TEXT_FIELDS } from '../engine/npcRoster.js';

const NAME_STOP_TOKENS = new Set(['the', 'a', 'an', 'of', 'von', 'van', 'de', 'da', 'la', 'le']);

/** Strips leading common titles and articles case-insensitively to get the core name (frozen 2026-11-07). */
function legacyCoreNpcName(name) {
    if (!name) return '';
    let core = name.trim();
    let prev;
    do {
        prev = core;
        core = core.replace(/^(?:the|a|an|high\s+priest(?:ess)?|grand\s+master|lord\s+commander|first\s+mate|confessor|brother-in-arms|sister-in-arms|brother|sister|magister|father|mother|captain|lord|lady|commander|sir|baron|king|queen|elder|magistrate|inquisitor|officer|warden|sheriff|constable|priest(?:ess)?|acolyte|abbot|cardinal|bishop|magus|archmage|archmagus|baroness|duke|duchess|prince|princess|count|countess|emperor|empress|master|mistress|doctor|general|sergeant|corporal|lieutenant|guard|sentry|innkeeper|blacksmith|merchant|saint|st\.?)\b\s*/gi, '');
    } while (core !== prev);
    return core.trim().toLowerCase();
}

function legacyMeaningfulNameTokens(name) {
    return legacyCoreNpcName(name)
        .split(/[^a-z0-9']+/)
        .filter(token => token.length > 1 && !NAME_STOP_TOKENS.has(token));
}

/**
 * `namesMatch` as of 2026-11-07: case-insensitive equality, equal core names
 * after title-stripping, or one name's meaningful tokens contained in the
 * other's ("Saima" ⊂ "Saima Aallotar"); generic creature or role names never
 * containment-match.
 */
export function legacyNamesMatch(name1, name2) {
    if (typeof name1 !== 'string' || typeof name2 !== 'string' || !name1 || !name2) return false;
    const n1 = name1.toLowerCase();
    const n2 = name2.toLowerCase();
    if (n1 === n2) return true;

    const core1 = legacyCoreNpcName(name1);
    const core2 = legacyCoreNpcName(name2);
    if (core1 && core2 && core1 === core2) return true;

    const tokens1 = legacyMeaningfulNameTokens(name1);
    const tokens2 = legacyMeaningfulNameTokens(name2);
    const [shortTokens, longTokens, shortName] = tokens1.length <= tokens2.length
        ? [tokens1, tokens2, name1]
        : [tokens2, tokens1, name2];
    if (shortTokens.length === 0) return false;
    if (isGenericCreatureName(shortName)) return false;
    const longSet = new Set(longTokens);
    return shortTokens.every(token => longSet.has(token));
}

function pruneRecordBlanks(record) {
    const out = {};
    for (const [key, value] of Object.entries(record)) {
        if (value === '' || value === null || value === undefined) continue;
        out[key] = value;
    }
    return out;
}

/**
 * `dedupeNpcRoster` as of 2026-11-07, which LOAD_GAME ran on every load:
 * forks of one person fold (the shorter token set contained in the longer);
 * the record with the longer name keeps its identity, dossier prose merges
 * through the normal fragment / restatement policy, bond moments and hooks
 * union with their own dedupe, and current-state fields come from whichever
 * record was seen last. Two distinct full names ("Maren Tull", "Maren
 * Ashford") never match and stay two people. The folded-away record's name
 * is kept as an ALIAS of the survivor, so the live exact lookup still finds
 * it under the name the fiction used.
 */
export function legacyFoldForkedNpcs(npcs = []) {
    const kept = [];
    for (const raw of Array.isArray(npcs) ? npcs : []) {
        const npc = raw || {};
        const matchIdx = kept.findIndex(existing => legacyNamesMatch(existing.name, npc.name));
        if (matchIdx === -1) {
            kept.push(npc);
            continue;
        }
        const other = kept[matchIdx];
        const [base, newer] = (npc.lastSeen || 0) >= (other.lastSeen || 0) ? [other, npc] : [npc, other];
        const longerName = (String(npc.name || '').length > String(other.name || '').length ? npc.name : other.name);
        const shorterName = longerName === npc.name ? other.name : npc.name;
        const merged = {
            ...base,
            ...pruneRecordBlanks(newer),
            name: longerName,
            aliases: [...new Set([...(base.aliases || []), ...(newer.aliases || []), shorterName].filter(a => typeof a === 'string' && a.trim() && a.trim().toLowerCase() !== String(longerName).trim().toLowerCase()))],
            id: other.id || npc.id,
            firstMet: Math.min(base.firstMet || Infinity, newer.firstMet || Infinity) === Infinity
                ? undefined
                : Math.min(base.firstMet || Infinity, newer.firstMet || Infinity),
            lastSeen: Math.max(base.lastSeen || 0, newer.lastSeen || 0) || undefined,
            // A zero stamp is kept when either side carried one (the load heal
            // writes 0 for a record with `lastSeen` and no stamp), so the fold
            // is idempotent; the 2026-11-07 code dropped it as falsy.
            lastSeenMessage: Number.isFinite(base.lastSeenMessage) || Number.isFinite(newer.lastSeenMessage)
                ? Math.max(base.lastSeenMessage || 0, newer.lastSeenMessage || 0)
                : undefined,
            pinned: !!(base.pinned || newer.pinned),
            trust: Number.isFinite(newer.trust) ? newer.trust : base.trust,
            kind: base.kind === 'character' || newer.kind === 'character' ? 'character' : (newer.kind || base.kind),
            rosterTier: base.rosterTier === 'character' || newer.rosterTier === 'character'
                ? 'character'
                : (newer.rosterTier || base.rosterTier),
            bondMoments: appendBondMoments(base.bondMoments, newer.bondMoments),
            recentImpressions: normalizeImpressions([...(base.recentImpressions || []), ...(newer.recentImpressions || [])]),
            callbackHooks: appendCallbackHooks(base.callbackHooks, newer.callbackHooks),
            knownFacts: [...new Set([...(base.knownFacts || []), ...(newer.knownFacts || [])])],
        };
        for (const field of NPC_DURABLE_TEXT_FIELDS) {
            merged[field] = mergeNpcDossierText(base[field], newer[field]);
        }
        // No undefined-valued keys: the load heals read "missing" by key, and
        // a key that is present-but-undefined made a second run heal what the
        // first had left alone.
        kept[matchIdx] = Object.fromEntries(Object.entries(normalizeNpcRecord(merged)).filter(([, value]) => value !== undefined));
    }
    return kept;
}

// `isRecordedDead` as of 2026-11-08 (before lane 6C): a note OPENING on "Killed"
// is the NPC's death only when nothing follows it but by/in/at/during or the
// end ("Killed by Vesa.", "Killed in combat.") — "Killed two guards and fled"
// is a living NPC's deed. Frozen for the save-version-5 migration, which turns
// the reading into the record's own `dead: true`; nothing in play reads notes.
const LEGACY_RECORDED_DEATH_RE = /^\s*(?:dead|died)\b|^\s*(?:killed|slain|executed|murdered)(?:\s+(?:by|in|at|during)\b|\s*[.;!]|\s*$)|\b(?:killed|slain|executed|murdered|beheaded)\s+(?:by|in)\b|\b(?:is|was|lies|lay)\s+(?:now\s+)?dead\b|\bdead\s+on\s+the\b/i;

/** The record's own latest note says this person is dead (frozen 2026-11-08). */
export function legacyRecordedDead(npc) {
    const notes = typeof npc?.lastNotes === 'string' ? npc.lastNotes.replace(/\s+/g, ' ').trim() : '';
    return LEGACY_RECORDED_DEATH_RE.test(notes);
}

/**
 * The name strings an old save holds about people, outside the roster: who a
 * quest was for, who a story card links, who witnessed or voiced a tell, who a
 * movement was with, who a record's ties regard, who knows a private fact.
 * These are what lane 7's exact lookups will read; the migration seeds each
 * one as an alias of the one record the frozen matcher resolved it to.
 */
export function legacyPeopleNamesInSave(save = {}) {
    const names = new Set();
    const add = (value) => {
        if (typeof value === 'string' && value.trim()) names.add(value.trim());
    };
    for (const quest of Array.isArray(save.quests) ? save.quests : []) add(quest?.patron);
    for (const card of Array.isArray(save.storyMemory) ? save.storyMemory : []) {
        for (const name of Array.isArray(card?.linkedNpcNames) ? card.linkedNpcNames : []) add(name);
    }
    for (const tell of Array.isArray(save.heroTells) ? save.heroTells : []) {
        for (const name of Array.isArray(tell?.witnesses) ? tell.witnesses : []) add(name);
        for (const name of Array.isArray(tell?.voicedBy) ? tell.voicedBy : []) add(name);
    }
    for (const entry of Array.isArray(save.ledger) ? save.ledger : []) add(entry?.party);
    for (const npc of Array.isArray(save.npcs) ? save.npcs : []) {
        for (const tie of Array.isArray(npc?.ties) ? npc.ties : []) add(tie?.name);
    }
    for (const fact of Array.isArray(save.worldFacts) ? save.worldFacts : []) {
        for (const name of Array.isArray(fact?.knownBy) ? fact.knownBy : []) add(name);
    }
    return [...names];
}
